    private void btnIniciarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciarActionPerformed
    int cantidad = modeloGrupos.getSize();
    if (modeloGrupos.getSize() < 2) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Debes registrar al menos 2 grupos para iniciar el sorteo."
    );
    return;
}

if (cantidad > 1) {

    btnIniciar.setEnabled(false);
    contadorAnimacion = 0;
    String[] nombres = new String[modeloGrupos.getSize()];

for (int i = 0; i < modeloGrupos.getSize(); i++) {
    nombres[i] = modeloGrupos.getElementAt(i);
}

carrera.establecerGrupos(nombres);
carrera.avisarFinCarrera(() -> {
    int posicion = carrera.obtenerUltimoCarrito();

    if (posicion >= 0 && posicion < modeloGrupos.getSize()) {
        String eliminado = modeloGrupos.getElementAt(posicion);

        modeloGrupos.removeElementAt(posicion);

        if (modeloGrupos.getSize() == 1) {
            String ganador = modeloGrupos.getElementAt(0);

            lblResultado.setText("🏆 GRAN GANADOR: " + ganador);
            lblResultado.setForeground(java.awt.Color.YELLOW);

            btnIniciar.setEnabled(false);

        } else {
            lblResultado.setText("ELIMINADO: " + eliminado);
            lblResultado.setForeground(java.awt.Color.RED);

            btnIniciar.setEnabled(true);
        }
    }
});
    carrera.iniciarCarrera();

  

} else if (cantidad == 1) {

    lblResultado.setText(
        "ÚLTIMO: " + modeloGrupos.getElementAt(0)
    );

    btnIniciar.setEnabled(false);
}

    }//GEN-LAST:event_btnIniciarActionPerformed

    private void btnReiniciarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReiniciarActionPerformed
     if (timerAnimacion != null) {
    timerAnimacion.stop();
}

modeloGrupos.clear();

for (String grupo : gruposOriginales) {
    modeloGrupos.addElement(grupo);
}

contadorAnimacion = 0;

lblResultado.setText("ESPERANDO SORTEO...");

btnIniciar.setEnabled(true);
    }//GEN-LAST:event_btnReiniciarActionPerformed

    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
       String nombre = txtGrupo.getText().trim();

if (nombre.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Escribe el nombre de un grupo."
    );
    return;
}

for (int i = 0; i < modeloGrupos.getSize(); i++) {
    if (modeloGrupos.getElementAt(i).equalsIgnoreCase(nombre)) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Ese grupo ya existe."
        );
        return;
    }
}

modeloGrupos.addElement(nombre);
gruposOriginales.add(nombre);

txtGrupo.setText("");
    }//GEN-LAST:event_btnAgregarActionPerformed

